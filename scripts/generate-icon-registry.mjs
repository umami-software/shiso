/**
 * Generates src/lib/icon-registry.generated.ts.
 *
 * Authors reference icons by name in MDX (`<Card icon="rocket">`). Importing all of
 * lucide-react to support that would pull in ~4000 modules, so instead we scan the
 * source for the icon names actually used and emit explicit named imports. The result
 * tree-shakes normally and renders synchronously during prerender.
 *
 * Run via `pnpm icons:registry`, or automatically by the Vite plugin in vite.config.ts.
 */
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import * as lucide from 'lucide-react';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUTPUT = path.join(ROOT, 'src/lib/icon-registry.generated.ts');
const SCAN_DIRS = ['content', 'src'];
const SCAN_EXTENSIONS = new Set(['.md', '.mdx', '.tsx']);

// Icons used by the docs component library itself, so pages always have a baseline set.
const ALWAYS_INCLUDE = ['rocket', 'code', 'book-open', 'circle-check', 'circle-alert'];

const ICON_ATTRIBUTE = /\bicon\s*=\s*["']([^"'{}\n]+)["']/g;

// docs.json declares icons as JSON properties rather than JSX/MDX attributes.
const ICON_JSON_PROPERTY = /"icon"\s*:\s*"([^"]+)"/g;
const NON_LUCIDE_ICONS = new Set([
  'bluesky',
  'discord',
  'facebook',
  'github',
  'hacker-news',
  'instagram',
  'linkedin',
  'medium',
  'reddit',
  'slack',
  'telegram',
  'threads',
  'twitter',
  'x',
  'x-twitter',
  'youtube',
]);

/** `circle-check`, `circle_check`, `CircleCheck` -> `circle-check` */
export function normalizeIconName(name) {
  return name
    .trim()
    .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    .replace(/[\s_]+/g, '-')
    .toLowerCase()
    .replace(/-+/g, '-')
    .replace(/^-|-$/g, '');
}

/** `circle-check` -> `CircleCheck` */
function toPascalCase(name) {
  return name
    .split('-')
    .filter(Boolean)
    .map(part => part.charAt(0).toUpperCase() + part.slice(1))
    .join('');
}

async function collectFiles(dir, files = []) {
  let entries;

  try {
    entries = await fs.readdir(dir, { withFileTypes: true });
  } catch {
    return files;
  }

  for (const entry of entries) {
    const fullPath = path.join(dir, entry.name);

    if (entry.isDirectory()) {
      if (entry.name === 'node_modules' || entry.name.startsWith('.')) {
        continue;
      }
      await collectFiles(fullPath, files);
    } else if (SCAN_EXTENSIONS.has(path.extname(entry.name))) {
      files.push(fullPath);
    }
  }

  return files;
}

function addMatches(names, source, pattern) {
  for (const match of source.matchAll(pattern)) {
    const value = match[1].trim();

    if (
      /^(?:https?:|data:image\/|\/|\.\.?\/)/i.test(value) ||
      /\.(?:avif|gif|jpe?g|png|svg|webp)(?:[?#].*)?$/i.test(value)
    ) {
      continue;
    }

    const normalized = normalizeIconName(value);

    if (normalized && /^[a-z0-9-]+$/.test(normalized)) {
      names.add(normalized);
    }
  }
}

async function findIconNames() {
  const names = new Set(ALWAYS_INCLUDE);

  for (const dir of SCAN_DIRS) {
    const files = await collectFiles(path.join(ROOT, dir));

    for (const file of files) {
      addMatches(names, await fs.readFile(file, 'utf8'), ICON_ATTRIBUTE);
    }
  }

  // Navigation and navbar icons live in docs.json, not in content or source.
  const config = await fs.readFile(path.join(ROOT, 'docs.json'), 'utf8').catch(() => '');
  addMatches(names, config, ICON_JSON_PROPERTY);

  return [...names].sort();
}

function renderModule(entries) {
  const imports = entries.map(({ component }) => `  ${component},`).join('\n');
  const mapping = entries
    .map(({ name, component }) => {
      // Match the formatter's "quote props as needed" style.
      const key = /^[A-Za-z_$][\w$]*$/.test(name) ? name : `'${name}'`;

      return `  ${key}: ${component},`;
    })
    .join('\n');

  return `// Generated by scripts/generate-icon-registry.mjs. Do not edit by hand.
// Add icons by using them in content (\`icon="name"\`) and rebuilding.
import {
${imports}
} from 'lucide-react';
import type { IconComponent } from '@/lib/icons';

export const ICON_REGISTRY: Record<string, IconComponent> = {
${mapping}
};
`;
}

export async function generateIconRegistry() {
  const names = await findIconNames();
  const entries = [];
  const unknown = [];

  for (const name of names) {
    if (NON_LUCIDE_ICONS.has(name)) {
      continue;
    }

    const component = toPascalCase(name);

    if (component in lucide) {
      entries.push({ name, component });
    } else {
      unknown.push(name);
    }
  }

  const contents = renderModule(entries);
  const previous = await fs.readFile(OUTPUT, 'utf8').catch(() => '');

  if (previous !== contents) {
    await fs.mkdir(path.dirname(OUTPUT), { recursive: true });
    await fs.writeFile(OUTPUT, contents);
  }

  return { count: entries.length, unknown, changed: previous !== contents };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { count, unknown } = await generateIconRegistry();

  console.log(`Icon registry: ${count} icons`);

  if (unknown.length) {
    console.warn(`Unknown icon names (not in lucide): ${unknown.join(', ')}`);
  }
}
