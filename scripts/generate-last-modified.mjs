/**
 * Generates src/lib/last-modified.generated.ts.
 *
 * The `metadata.timestamp` config key shows a last-modified date on pages.
 * That date comes from git history, which only exists at build time, so a
 * single `git log` pass over the repo maps every content file to the date of
 * the latest commit that touched it. Files not committed yet fall back to
 * filesystem mtime.
 *
 * Run via `pnpm timestamps`, or automatically by the Vite plugin in vite.config.ts.
 */
import { execFile } from 'node:child_process';
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { promisify } from 'node:util';

const execFileAsync = promisify(execFile);

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUTPUT = path.join(ROOT, 'src/lib/last-modified.generated.ts');
const CONTENT_EXTENSIONS = new Set(['.md', '.mdx']);

async function collectContentFiles(dir, files = []) {
  let entries;

  try {
    entries = await fs.readdir(dir, { withFileTypes: true });
  } catch {
    return files;
  }

  for (const entry of entries) {
    const fullPath = path.join(dir, entry.name);

    if (entry.isDirectory()) {
      await collectContentFiles(fullPath, files);
    } else if (CONTENT_EXTENSIONS.has(path.extname(entry.name))) {
      files.push(fullPath);
    }
  }

  return files;
}

/** Latest commit date per repo path, from one newest-first `git log` pass. */
async function getGitDates() {
  const dates = new Map();

  try {
    const { stdout } = await execFileAsync(
      'git',
      ['-c', 'core.quotePath=false', 'log', '--format=@%cI', '--name-only', '--', 'content'],
      { cwd: ROOT, maxBuffer: 64 * 1024 * 1024 },
    );

    let current = '';

    for (const line of stdout.split('\n')) {
      if (line.startsWith('@')) {
        current = line.slice(1).trim();
      } else if (line.trim() && current && !dates.has(line.trim())) {
        dates.set(line.trim(), current);
      }
    }
  } catch {
    // Not a git checkout (e.g. a tarball build); every file uses mtime.
  }

  return dates;
}

export async function generateLastModified() {
  const files = await collectContentFiles(path.join(ROOT, 'content'));
  const gitDates = await getGitDates();
  const entries = [];

  for (const file of files.sort()) {
    const repoPath = path.relative(ROOT, file).split(path.sep).join('/');
    let date = gitDates.get(repoPath);

    if (!date) {
      const stat = await fs.stat(file);
      date = stat.mtime.toISOString();
    }

    // Module keys as produced by import.meta.glob: "/content/docs/index.mdx".
    entries.push([`/${repoPath}`, date]);
  }

  const mapping = entries.map(([key, date]) => `  '${key}': '${date}',`).join('\n');
  const contents = `// Generated by scripts/generate-last-modified.mjs. Do not edit by hand.
export const LAST_MODIFIED: Record<string, string> = {
${mapping}
};
`;

  const previous = await fs.readFile(OUTPUT, 'utf8').catch(() => '');

  if (previous !== contents) {
    await fs.mkdir(path.dirname(OUTPUT), { recursive: true });
    await fs.writeFile(OUTPUT, contents);
  }

  return { count: entries.length, changed: previous !== contents };
}

if (process.argv[1] && pathToFileURL(path.resolve(process.argv[1])).href === import.meta.url) {
  const { count } = await generateLastModified();
  console.log(`Last-modified dates: ${count} files`);
}
